"""Export approved SVG masters to local alpha PNGs and static Metro requires.

Generation uses the already available CairoSVG tool. --check and tests use only
the standard library and verify source/config, dimensions and asset fingerprints.
No renderer or package is added to the app or CI runtime.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import xml.etree.ElementTree as ET
import zlib

ROOT = Path(__file__).resolve().parents[1]
MASTER = Path('docs/product/design/symbols/glyphs.svg')
DEST = Path('apps/platform-lab/assets/icons/duotone')
REGISTRY = Path('apps/platform-lab/src/mobile/duotone-assets.ts')
GLYPHS = ['home', 'flight-paper-plane', 'book', 'club', 'sparkle', 'back', 'chain',
          'medical-card', 'profile', 'logbook', 'glider', 'clock', 'location',
          'weather', 'duty', 'calendar-neutral', 'messages', 'search', 'filter',
          'down', 'refresh', 'info', 'right', 'arrow', 'send', 'check', 'plus',
          'minus', 'close', 'chart']
TONES = {
    'default': ['#32f1ef', '#00d9e8', '#00b9df', '#8caac1', '#7094b1', '#46688b'],
    'muted': ['#b6c8d8', '#99b0c6', '#7d98af', '#839fb7', '#67859f', '#46627b'],
    'paper': ['#ffe0b4', '#ffa34e', '#ff772d', '#bd926f', '#a27658', '#715543'],
    'assistant': ['#ecd6ff', '#d39bff', '#ad75f5', '#b7a5d6', '#9483b9', '#6d5c91'],
    'contrast': ['#123a50', '#0d2e44', '#082238', '#45657a', '#294b63', '#19394f'],
}


def sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def has_visible_alpha(blob: bytes, size: int) -> bool:
    """Zero alpha stays zero through every PNG filter (channels are independent).

    At least one nonzero filtered alpha is necessary and sufficient for any
    visible pixel in a noninterlaced 8-bit RGBA PNG. No image library is needed.
    """
    if blob[24] != 8 or blob[28] != 0:
        raise ValueError('Expected noninterlaced 8-bit native icon')
    position, chunks = 8, []
    while position < len(blob):
        length = struct.unpack('>I', blob[position:position + 4])[0]
        if blob[position + 4:position + 8] == b'IDAT':
            chunks.append(blob[position + 8:position + 8 + length])
        position += length + 12
    raw = zlib.decompress(b''.join(chunks))
    stride = size * 4
    if len(raw) != size * (stride + 1):
        raise ValueError('Unexpected RGBA pixel length')
    return any(any(raw[row + 4:row + stride + 1:4]) for row in range(0, len(raw), stride + 1))


def svg_assets(root: Path = ROOT) -> tuple[dict[str, bytes], dict]:
    source = (root / MASTER).read_text(encoding='utf-8').encode('utf-8')
    tree = ET.fromstring(source)
    ns = '{http://www.w3.org/2000/svg}'
    ET.register_namespace('', ns[1:-1])
    symbols = {s.attrib['id']: s for s in tree.findall(ns + 'symbol')}
    defs = ET.tostring(tree.find(ns + 'defs'), encoding='unicode')
    result = {}
    for name in GLYPHS:
        symbol = symbols[name]
        body = re.sub(r'<symbol\b[^>]*>', '<g>', ET.tostring(symbol, encoding='unicode')).replace('</symbol>', '</g>')
        for tone, palette in TONES.items():
            svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96">{defs}{body}</svg>'
            for before, after in zip(TONES['default'], palette):
                svg = svg.replace(before, after)
            result[f'{name}-{tone}.png'] = svg.encode('utf-8')
    config = {'master_sha256': sha(source), 'glyphs': GLYPHS, 'tones': TONES,
              'size_px': 192, 'glider_size_px': 288, 'selection': {'H04': 'medical-card', 'N02': 'flight-paper-plane'}}
    return result, config


def registry_text() -> str:
    lines = ['// Generated by python scripts/duotone_icons.py; local alpha PNGs, no icon runtime.',
             'export const duotoneAssets = {']
    for name in GLYPHS:
        lines.append(f"  '{name}': {{")
        lines.extend(f"    {tone}: require('../../assets/icons/duotone/{name}-{tone}.png')," for tone in TONES)
        lines.append('  },')
    lines += ['} as const;', 'export type SymbolName = keyof typeof duotoneAssets;',
              "export type SymbolTone = keyof typeof duotoneAssets['home'];", '']
    return '\n'.join(lines)


def check(root: Path = ROOT) -> dict:
    _, config = svg_assets(root)
    manifest = json.loads((root / DEST / 'manifest.json').read_text(encoding='utf-8'))
    if manifest['config'] != config:
        raise ValueError('Native icon source/config changed; regenerate assets')
    if (root / REGISTRY).read_text(encoding='utf-8') != registry_text():
        raise ValueError('Static Metro registry is stale')
    expected = {f'{name}-{tone}.png' for name in GLYPHS for tone in TONES}
    if set(manifest['assets']) != expected:
        raise ValueError('Incomplete native icon asset family')
    for filename, record in manifest['assets'].items():
        blob = (root / DEST / filename).read_bytes()
        size = 288 if filename.startswith('glider-') else 192
        if blob[:8] != b'\x89PNG\r\n\x1a\n' or struct.unpack('>II', blob[16:24]) != (size, size) or blob[25] != 6:
            raise ValueError('Expected sized RGBA PNG: ' + filename)
        if not has_visible_alpha(blob, size):
            raise ValueError('Empty native icon: ' + filename)
        if sha(blob) != record['sha256']:
            raise ValueError('Native icon bytes changed: ' + filename)
    return {'assets': len(expected), 'tones': len(TONES), 'glyphs': len(GLYPHS), 'status': 'fresh'}


def generate(root: Path = ROOT) -> dict:
    import cairosvg
    assets, config = svg_assets(root)
    dest = root / DEST
    dest.mkdir(parents=True, exist_ok=True)
    records = {}
    for filename, source in assets.items():
        size = 288 if filename.startswith('glider-') else 192
        png = cairosvg.svg2png(bytestring=source, output_width=size, output_height=size)
        (dest / filename).write_bytes(png)
        records[filename] = {'sha256': sha(png), 'size_px': size}
    manifest = {'config': config, 'renderer': 'CairoSVG ' + cairosvg.__version__, 'assets': records}
    (dest / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
    (root / REGISTRY).write_text(registry_text(), encoding='utf-8', newline='\n')
    return check(root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(json.dumps(check() if args.check else generate()))
        return 0
    except (ValueError, OSError, KeyError, ImportError) as exc:
        print('Duotone asset error: ' + str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
